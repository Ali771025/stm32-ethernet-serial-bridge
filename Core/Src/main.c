/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* init code for LWIP */
  MX_LWIP_Init();
  /* USER CODE BEGIN 5 */
  UART_HandleTypeDef *const uart_handles[UART_SERVICE_CHANNEL_COUNT] =
  {
    &huart1, &huart2, &huart3, &huart4,
    &huart5, &huart6, &huart7, &huart8
  };
  uint32_t uart_event_bits = UART_SERVICE_ALL_CHANNEL_BITS;
  uint32_t supervisor_last_evaluation_ms = HAL_GetTick();

  if (uart_service_start(uart_handles,
                         xTaskGetCurrentTaskHandle()) != UART_SERVICE_OK)
  {
    platform_fault_raise(PLATFORM_FAULT_UART_SERVICE_START,
                         __FILE__,
                         (uint32_t)__LINE__);
  }
  /* Infinite loop */
  for(;;)
  {
    uint32_t now_ms = HAL_GetTick();
    uint32_t stack_free_words = 0U;
    platform_health_t health;

#if (INCLUDE_uxTaskGetStackHighWaterMark == 1)
    stack_free_words = (uint32_t)uxTaskGetStackHighWaterMark(NULL);
#endif
    platform_supervisor_heartbeat(PLATFORM_SUPERVISOR_TASK_APP,
                                  now_ms,
                                  stack_free_words);
    (void)uart_service_process(uart_event_bits);
    net_bridge_poll(now_ms);
    app_baseline_poll(now_ms);
    eth_bringup_diag_poll(now_ms);
    if ((uint32_t)(now_ms - supervisor_last_evaluation_ms) >= 50U)
    {
      platform_supervisor_snapshot_t supervisor_snapshot;
      supervisor_last_evaluation_ms = now_ms;
      health = platform_supervisor_evaluate(now_ms);
      if (health == PLATFORM_HEALTH_FAULT_TASK)
      {
        platform_supervisor_get_snapshot(&supervisor_snapshot);
        platform_reset_note_supervisor(supervisor_snapshot.stale_task_mask,
                                       (uint32_t)health);
      }
    }
    uart_event_bits = 0U;
    (void)xTaskNotifyWait(0U,
                          UINT32_MAX,
                          &uart_event_bits,
                          pdMS_TO_TICKS(1U));
  }
  /* USER CODE END 5 */
}

